"""Generate docs/RESULTS.md from a fresh default run of every model.

Run from the project root:
    backend\\.venv\\Scripts\\python.exe reports\\generate_results.py
"""
from __future__ import annotations

import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from engine.bayesian import solve_bayesian  # noqa: E402
from engine.config import build_config  # noqa: E402
from engine.insights import generate  # noqa: E402
from engine.registry import COMPARISON_MODELS, MODEL_INFO, compare, solve  # noqa: E402
from engine.repeated import solve_repeated  # noqa: E402
from simulation.runner import validate_scenarios  # noqa: E402


def money(x):
    return f"{'−' if x < 0 else ''}₹{abs(x):,.0f}"


def main():
    cfg = build_config()
    comp = compare(cfg)
    rows = {(r["model"], r["scenario"]): r for r in comp["rows"]}
    scen = comp["scenarios"]
    out = [
        "# Results (default configuration)",
        "",
        f"_Generated by `reports/generate_results.py` on {date.today().isoformat()} from "
        "`backend/config/defaults.json`. All values are per peak hour in one city zone. Re-run the script after "
        "changing the configuration._",
        "",
        f"**Verification:** {sum(r['verified'] for r in comp['rows'])} of {len(comp['rows'])} model × scenario "
        "equilibria/optima pass the unilateral-deviation (or optimality) grid check.",
        "",
        "## 1. Key findings",
        "",
    ]
    for i, ins in enumerate(generate(cfg)["insights"], 1):
        title = ins["title"] if ins["title"].endswith("?") else ins["title"] + "."
        out += [f"{i}. **{title}** {ins['text']}", ""]

    out += ["## 2. Cross-model comparison", ""]
    for s in scen:
        out += [f"### {s} demand (Λ = {comp['demand'][s]} orders/h)", "",
                "| Model | Strategy (A / B) | Delay (min) | Orders/h | Unserved | Profit (total) | Incentive spend | CS | Rider surplus | Welfare | Efficiency | PoA |",
                "|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for m in COMPARISON_MODELS:
            r = rows[(m, s)]
            out.append(f"| {MODEL_INFO[m]['label']} | {r['variable']} = {r['strategy_A']:.1f} / {r['strategy_B']:.1f} | "
                       f"{r['avg_delay']:.1f} | {r['total_completed']:.0f} | {r['total_unserved']:.1f} | {money(r['total_profit'])} | "
                       f"{money(r['total_incentive_spend'])} | {money(r['consumer_surplus'])} | {money(r['rider_surplus'])} | "
                       f"{money(r['total_welfare'])} | {r['efficiency'] * 100:.1f}% | {r['price_of_anarchy']:.3f} |")
        out.append("")

    out += ["## 3. Leader–follower games", "",
            "| Demand | Capacity leader N (A / B) | FMA capacity | Incentive leader w (A / B) | FMA incentive | Follower gain (incentive) | Two-stage N | Cournot N | Two-stage fee |",
            "|---|---|---|---|---|---|---|---|---|"]
    for s in scen:
        cap = solve("stackelberg_capacity", cfg, s, curves=False)
        inc = solve("stackelberg_incentive", cfg, s, curves=False)
        ts = rows[("two_stage", s)]
        cn = rows[("cournot", s)]
        out.append(f"| {s} | {cap['equilibrium']['A']:.1f} / {cap['equilibrium']['B']:.1f} | {money(cap['extras']['first_mover_advantage'])} | "
                   f"{inc['equilibrium']['A']:.1f} / {inc['equilibrium']['B']:.1f} | {money(inc['extras']['first_mover_advantage'])} | "
                   f"{money(inc['extras']['follower_change'])} | {ts['N_A']:.1f} | {cn['N_A']:.1f} | ₹{ts['p_A']:.1f} |")
    out.append("")

    out += ["## 4. Strategic-form and repeated game", "",
            "| Demand | Low w (collusive) | High w (best deviation) | 2×2 structure | T | R | P | S | δ* (grim) | δ* (Nash reversion) | Tournament winner (δ = 0.9) |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    for s in scen:
        r = solve_repeated(cfg, s)
        sg = r["stage_game"]
        out.append(f"| {s} | ₹{r['levels']['cooperate']:.1f} | ₹{r['levels']['defect']:.1f} | {sg['classification']['label']} | "
                   f"{money(sg['T'])} | {money(sg['R'])} | {money(sg['P'])} | {money(sg['S'])} | {r['delta_star']:.3f} | "
                   f"{r['delta_star_nash_reversion']:.3f} | {r['tournament']['ranking'][0]['name']} |")
    r = solve_repeated(cfg, "Medium", noise=0.05)
    sweep = {p["noise"]: p for p in r["noise_sweep"]}
    out += ["", f"With 5 % observation noise (Medium demand), the share of days on which both platforms cooperate is "
            f"{sweep[0.05]['GRIM'] * 100:.0f}% under Grim Trigger, {sweep[0.05]['TFT'] * 100:.0f}% under Tit-for-Tat and "
            f"{sweep[0.05]['GTFT'] * 100:.0f}% under Generous Tit-for-Tat.", ""]

    b = solve_bayesian(cfg, "Peak")
    st = b["strategies"]
    out += ["## 5. Bayesian Cournot (Peak demand, P(High) = 0.5, Δa = 0.3)", "",
            f"Type-contingent capacities: A(H) = {st['A']['H']:.1f}, A(L) = {st['A']['L']:.1f}, "
            f"B(H) = {st['B']['H']:.1f}, B(L) = {st['B']['L']:.1f} riders. Verified per type: {b['verification']['passed']}.", "",
            "| Types (A, B) | Prob. | BNE N (A / B) | Complete-info N (A / B) | Delay (A / B) | Profit (A / B) |",
            "|---|---|---|---|---|---|"]
    for p in b["profiles"]:
        out.append(f"| {p['types'][0]}, {p['types'][1]} | {p['probability']:.2f} | {p['N'][0]:.1f} / {p['N'][1]:.1f} | "
                   f"{p['complete_info_N'][0]:.1f} / {p['complete_info_N'][1]:.1f} | {p['delay'][0]:.1f} / {p['delay'][1]:.1f} | "
                   f"{money(p['profit'][0])} / {money(p['profit'][1])} |")
    out += ["", f"Expected value of information for A: {money(b['expected']['value_of_information'][0])}/h.", ""]

    v = validate_scenarios(cfg, runs=10)
    f = v["fitted_delay_curve"]
    out += ["## 6. Agent-based validation of the delay function", "",
            f"{v['runs']} Monte Carlo seeds per scenario, incentives from the Bertrand (incentive) equilibrium.", "",
            "| Demand | Platform | Simulated mean delay (95% CI) | Analytical (quasi-static) | Per-minute MAE | MAPE | Mean ρ | Cancelled (3 h) |",
            "|---|---|---|---|---|---|---|---|"]
    for r in v["rows"]:
        out.append(f"| {r['scenario']} | {r['platform']} | {r['sim_mean']:.1f} ({r['sim_lo']:.1f}–{r['sim_hi']:.1f}) | "
                   f"{r['analytic_realized']:.1f} | {r['mae']:.1f} min | {r['mape'] * 100:.0f}% | {r['rho']:.2f} | {r['cancelled']:.0f} |")
    out += ["", f"Overall per-minute MAPE: {v['overall_mape'] * 100:.0f}%. A delay curve fitted to the simulated minutes gives "
            f"d0 = {f['d0']:.1f} min and s = {f['s']:.2f} min (model: d0 = {cfg['market']['d0']}, s = {cfg['market']['s']}). "
            "The simulation's many-server fleet barely queues until utilisation approaches 1, so the analytical function is "
            "conservative at moderate load and close at peak.", "",
            "## 7. Figures", "",
            "Run `backend\\.venv\\Scripts\\python.exe reports\\make_figures.py` to regenerate the PNGs in `reports/figures/`:", ""]
    for p in sorted((ROOT / "reports" / "figures").glob("*.png")):
        out.append(f"- `reports/figures/{p.name}`")
    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote docs/RESULTS.md")


if __name__ == "__main__":
    main()
